#!/usr/bin/env bash
source /data-ssd/zhongchengkai/agnes/scripts/use-phase10-env.sh
export FINAL_ROOT=/data-ssd/zhongchengkai/agnes
export HOME="$FINAL_ROOT/.final-rescue-home" TMPDIR="$FINAL_ROOT/.tmp/final_rescue"
export TMP_DIR="$TMPDIR" TMP="$TMPDIR" TEMP="$TMPDIR"
export XDG_CONFIG_HOME="$HOME/.config" XDG_DATA_HOME="$HOME/.local/share" XDG_CACHE_HOME="$FINAL_ROOT/.cache/final_rescue"
export ROS_HOME="$HOME/.ros" ROS_LOG_DIR="$FINAL_ROOT/logs/final_rescue/ros"
export ROS_DOMAIN_ID=106 GZ_PARTITION=agnes_final_rescue PHASE9_STACK=final_rescue
export GZ_SIM_RESOURCE_PATH="$FINAL_ROOT/simulation/final_rescue"
export GZ_LOG_PATH="$FINAL_ROOT/logs/final_rescue/gazebo"
export ROBOT_NAV2_PARAMS="$FINAL_ROOT/simulation/final_rescue/nav2_params.yaml"
export ROBOT_WORLD_REGISTRY="$FINAL_ROOT/simulation/final_rescue/world_registry.json"
export ROBOT_GATEWAY=ros2 ROBOT_ROS2_ENV=final_rescue ROBOT_PERCEPTION=vlm
# Managed MCP navigation uses a bounded confirmation response and exposes the
# still-owned Nav2 operation through get_robot_state.  This keeps the fixed
# eight-tool contract while avoiding the MCP SDK's 60s request deadline.
export ROBOT_NAVIGATION_ASYNC=1 ROBOT_NAVIGATION_CONFIRMATION_MS=20000
export ROBOT_NAVIGATION_ACTION_BUDGET_SEC=180 ROBOT_NAVIGATION_RPC_BUDGET_MS=180000
export ROBOT_MISSION_ORIGIN_FILE="$FINAL_ROOT/runtime/interactive-mission-origin.json"
export FINAL_RUN_DIR="${FINAL_RUN_DIR:-$FINAL_ROOT/artifacts/final_rescue/manual}"
export ROBOT_TRACE_DIR="$FINAL_RUN_DIR"
export AGH_HOME="$FINAL_ROOT/.agh-home-step7" AGNES_PROFILE=local-dev
export AGNES_MCP_STDIO_ALLOWLIST="$FINAL_ROOT/tools/node/bin/node"
export PATH="$FINAL_ROOT/tools/node/bin:$PATH"
# Keep provider traffic on the already configured local proxy.  Older project
# stages hard-coded 7898; on shared hosts the active local proxy can move to a
# different port.  Select only a loopback listener and keep all proxy aliases
# consistent so Node and curl use the same route.  No external endpoint or
# credential is introduced here.
proxy_is_listening() {
  local value="$1" host port
  [[ "$value" =~ ^https?://([^:/]+):([0-9]+)$ ]] || return 1
  host="${BASH_REMATCH[1]}"; port="${BASH_REMATCH[2]}"
  [[ "$host" == "127.0.0.1" || "$host" == "localhost" ]] || return 1
  (exec 3<>"/dev/tcp/$host/$port") 2>/dev/null
}
proxy_candidates=("${AGNES_PROXY_URL:-}" "${ALL_PROXY:-}" "${HTTP_PROXY:-}" \
  "http://127.0.0.1:8118" "http://127.0.0.1:7898" "http://127.0.0.1:7899")
ACTIVE_PROXY=""
for candidate in "${proxy_candidates[@]}"; do
  [[ -n "$candidate" ]] || continue
  if proxy_is_listening "$candidate"; then ACTIVE_PROXY="$candidate"; break; fi
done
if [[ -n "$ACTIVE_PROXY" ]]; then
  export HTTP_PROXY="$ACTIVE_PROXY" HTTPS_PROXY="$ACTIVE_PROXY"
  export http_proxy="$ACTIVE_PROXY" https_proxy="$ACTIVE_PROXY"
fi
export NO_PROXY=127.0.0.1,localhost no_proxy=127.0.0.1,localhost NODE_USE_ENV_PROXY=1

# ScenarioManager may select a reviewed, project-local layout.  The file is
# data-only and is generated by scripts/interactive/scenario-manager.mjs.
# Keep the stable final_rescue defaults when no scenario has been selected.
SCENARIO_ENV_FILE="$FINAL_ROOT/artifacts/interactive-live/current-scenario.env"
if [[ -f "$SCENARIO_ENV_FILE" ]]; then
  source "$SCENARIO_ENV_FILE"
  scenario_path() { [[ "$1" = /* ]] && printf '%s' "$1" || printf '%s/%s' "$FINAL_ROOT" "$1"; }
  export SCENARIO_WORLD="$(scenario_path "$SCENARIO_WORLD")"
  export SCENARIO_MAP="$(scenario_path "$SCENARIO_MAP")"
  export SCENARIO_NAV2_PARAMS="$(scenario_path "$SCENARIO_NAV2_PARAMS")"
  export SCENARIO_BRIDGE="$(scenario_path "$SCENARIO_BRIDGE")"
  export SCENARIO_REGISTRY="$(scenario_path "$SCENARIO_REGISTRY")"
  export SCENARIO_DYNAMIC_CONTROLLER="$(scenario_path "$SCENARIO_DYNAMIC_CONTROLLER")"
  export ROBOT_NAV2_PARAMS="$SCENARIO_NAV2_PARAMS"
  export ROBOT_WORLD_REGISTRY="$SCENARIO_REGISTRY"
  export GZ_SIM_RESOURCE_PATH="$(dirname "$SCENARIO_WORLD")"
  export SCENARIO_WORLD_NAME="${SCENARIO_WORLD_NAME:-$SCENARIO_ID}"
fi
# An imported skeleton is an explicit activation, so it takes precedence over
# the reviewed random scenario while active.  It contains only map-prior
# geometry; interior state is still created by the physical scenario runtime.
IMPORTED_ENV_FILE="$FINAL_ROOT/artifacts/interactive-live/imported-map.env"
if [[ -f "$IMPORTED_ENV_FILE" ]]; then
  source "$IMPORTED_ENV_FILE"
  export ROBOT_NAV2_PARAMS="$SCENARIO_NAV2_PARAMS"
  export ROBOT_WORLD_REGISTRY="$SCENARIO_REGISTRY"
  export GZ_SIM_RESOURCE_PATH="$(dirname "$SCENARIO_WORLD")"
  export SCENARIO_WORLD_NAME="${SCENARIO_WORLD_NAME:-imported_building}"
fi
mkdir -p "$HOME" "$TMPDIR" "$XDG_CONFIG_HOME" "$XDG_DATA_HOME" "$XDG_CACHE_HOME" "$ROS_HOME" "$ROS_LOG_DIR" "$GZ_LOG_PATH" "$FINAL_RUN_DIR"
